#!/usr/bin/env python3
"""
make_appendix_tables.py -- coherence message logs for Appendix A of the report,
built from the existing result files (no new simulation is run).

    python3 make_appendix_tables.py ../ell305-termpaper/data/appendix_tables.tex

Message classes (report Table tab:msg-classes / Sarangi's bus messages):
  Read      = read miss  (BusRd,  Sarangi's readmiss)    8 B request + 72 B data
  RdX       = write miss (BusRdX, read-for-ownership)    8 B request + 72 B data
  Invalidate= upgrade    (BusUpgr, Sarangi's write)      8 B
  WB        = writeback: forced (M->S on a remote read), eviction, end of run  72 B
Each row is checked: 8*control + 72*(data + writebacks) must equal the
simulator's byte total.
"""
import sys
import pandas as pd

OUT = sys.argv[1] if len(sys.argv) > 1 else "appendix_tables.tex"
lines = ["% generated by make_appendix_tables.py from results/*.csv -- do not edit by hand"]


def row_counts(r):
    fwb = int(round(r.B_fwb / 72))
    ctrl = r.read_miss + r.write_miss + r.upgrades
    data = r.read_miss + r.write_miss
    wbs = fwb + r.evict_wb + r.drain_wb
    total_b = 8 * ctrl + 72 * (data + wbs)
    assert abs(total_b - r.B_tot) < 1e-6, (total_b, r.B_tot)
    return fwb, ctrl, data, wbs


def fmt(x):
    return f"{x:,.0f}"


def table_T1(d, label):
    df = pd.read_csv("results/sweep_main.csv")
    t = df[(df.d == d) & (df.pc_write_p == 0.3)]
    lines.append(r"\begin{table}[htbp]")
    lines.append(r"\centering")
    lines.append(rf"\caption{{Coherence message log, experiment T1, $d = {d:g}$, producer write probability 0.3: messages per run of 60\,000 accesses, mean of three seeds. Read $=$ read miss (BusRd), RdX $=$ write miss (read-for-ownership), Inv.\ $=$ upgrade (invalidate), WB $=$ writebacks (forced / eviction / end of run).}}")
    lines.append(rf"\label{{{label}}}")
    lines.append(r"\footnotesize")
    lines.append(r"\begin{tabular}{@{}r l r r r r r r r r@{}}")
    lines.append(r"\toprule")
    lines.append(r"$N$ & Protocol & Read & RdX & Inv. & WB forced & WB evict & WB end & Messages & Kbytes \\")
    lines.append(r"\midrule")
    for N in (2, 4, 8, 16):
        for p in ("MSI", "MESI", "MOESI"):
            rs = t[(t.N == N) & (t.protocol == p)]
            vals = []
            for _, r in rs.iterrows():
                fwb, ctrl, data, wbs = row_counts(r)
                vals.append(dict(rd=r.read_miss, rdx=r.write_miss, inv=r.upgrades, fwb=fwb,
                                 ev=r.evict_wb, end=r.drain_wb, msgs=ctrl + data + wbs, kb=r.B_tot / 1000))
            m = pd.DataFrame(vals).mean()
            lines.append(f"{N if p == 'MSI' else ''} & {p} & {fmt(m.rd)} & {fmt(m.rdx)} & {fmt(m.inv)} & "
                         f"{fmt(m.fwb)} & {fmt(m.ev)} & {fmt(m.end)} & {fmt(m.msgs)} & {m.kb:,.1f} \\\\")
        if N != 16:
            lines.append(r"\addlinespace[2pt]")
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    lines.append(r"\end{table}")
    lines.append("")


def table_T2(label):
    c = pd.read_csv("results/sweep_cachesize.csv")
    t = c[c.d == 0.5]
    lines.append(r"\begin{table}[htbp]")
    lines.append(r"\centering")
    lines.append(r"\caption{Coherence message log, experiment T2 (8 cores, $d = 0.5$): messages per run against private cache capacity, mean of three seeds. Columns as in \cref{tab:log-t1-d0p1}.}")
    lines.append(rf"\label{{{label}}}")
    lines.append(r"\footnotesize")
    lines.append(r"\begin{tabular}{@{}r l r r r r r r r r@{}}")
    lines.append(r"\toprule")
    lines.append(r"Blocks & Protocol & Read & RdX & Inv. & WB forced & WB evict & WB end & Messages & Kbytes \\")
    lines.append(r"\midrule")
    for cap in sorted(t.cap.unique()):
        for p in ("MSI", "MESI", "MOESI"):
            rs = t[(t.cap == cap) & (t.protocol == p)]
            vals = []
            for _, r in rs.iterrows():
                fwb, ctrl, data, wbs = row_counts(r)
                vals.append(dict(rd=r.read_miss, rdx=r.write_miss, inv=r.upgrades, fwb=fwb,
                                 ev=r.evict_wb, end=r.drain_wb, msgs=ctrl + data + wbs, kb=r.B_tot / 1000))
            m = pd.DataFrame(vals).mean()
            lines.append(f"{int(cap) if p == 'MSI' else ''} & {p} & {fmt(m.rd)} & {fmt(m.rdx)} & {fmt(m.inv)} & "
                         f"{fmt(m.fwb)} & {fmt(m.ev)} & {fmt(m.end)} & {fmt(m.msgs)} & {m.kb:,.1f} \\\\")
        if cap != max(t.cap):
            lines.append(r"\addlinespace[2pt]")
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    lines.append(r"\end{table}")
    lines.append("")


table_T1(0.02, "tab:log-t1-d0p02")
table_T1(0.1, "tab:log-t1-d0p1")
table_T1(0.5, "tab:log-t1-d0p5")
table_T2("tab:log-t2")
open(OUT, "w").write("\n".join(lines) + "\n")
print("wrote", OUT, "-- all rows passed the byte check")
